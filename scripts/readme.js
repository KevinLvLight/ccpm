// 重新生成 README.md（英文）和 README.zh-CN.md（中文）里 <!-- usage:start --> 到 <!-- usage:end --> 之间的“用法”一节
import { readFileSync, writeFileSync } from 'node:fs';
import { COMMAND_NAMES, helpText } from '../src/help.js';
import * as zh from '../src/i18n/help.zh.js';
import * as en from '../src/i18n/help.en.js';

const block = (s) => '```text\n' + s + '\n```';
const usage = (h, l) => [
  block(helpText(undefined, h)),
  l.commands,
  ...COMMAND_NAMES.map((c) => `#### ccpm ${c}\n\n${block(helpText(c, h))}`),
  l.concepts,
  block(helpText('concepts', h)),
  l.trouble,
  block(helpText('troubleshooting', h)),
].join('\n\n');

for (const [file, h, l] of [
  ['README.md', en, { commands: '### Commands in detail', concepts: '### Concepts', trouble: '### Troubleshooting' }],
  ['README.zh-CN.md', zh, { commands: '### 各命令详细说明', concepts: '### 概念说明', trouble: '### 排错指南' }],
]) {
  const url = new URL(`../${file}`, import.meta.url);
  const s = readFileSync(url, 'utf8');
  const a = s.indexOf('<!-- usage:start -->');
  const b = s.indexOf('<!-- usage:end -->');
  if (a < 0 || b < a) throw new Error(`${file}: usage markers not found`);
  writeFileSync(url, `${s.slice(0, a)}<!-- usage:start -->\n<!-- generated by node scripts/readme.js — do not edit by hand -->\n\n${usage(h, l)}\n\n${s.slice(b)}`);
  console.log(`updated ${file}`);
}
